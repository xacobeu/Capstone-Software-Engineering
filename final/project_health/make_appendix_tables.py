"""Generates the Appendix A candidate tables from account_candidates.json and account_decisions.json."""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CANDIDATES_IN = Path(__file__).resolve().parent / "data" / "account_candidates.json"
DECISIONS_IN = HERE / "account_decisions.json"
OUT = Path(__file__).resolve().parent.parent / "drafts" / "appendix_A_tables.tex"


def tex(s: str) -> str:
    for a, b in (("\\", "\\textbackslash{}"), ("_", "\\_"), ("%", "\\%"), ("#", "\\#"), ("&", "\\&"), ("$", "\\$"),
                 ("{", "\\{"), ("}", "\\}"), ("@", "@")):
        s = s.replace(a, b)
    return s


def decision(login: str, d: dict) -> str:
    for key, label in (("bots", "Bot, excluded"), ("spam_accounts", "Spam, excluded"),
                       ("shared_accounts", "Shared account, excluded")):
        if login in d[key]:
            return label
    return "Human, kept"


def main() -> None:
    c = json.loads(CANDIDATES_IN.read_text(encoding="utf-8"))
    d = json.loads(DECISIONS_IN.read_text(encoding="utf-8"))
    skew_only = [b for b in c["bot_candidates"]
                 if all(r.startswith("Task skew") for r in b["reasons"]) and decision(b["login"], d) == "Human, kept"
                 and b["login"] not in d["humans"]]
    listed = [b for b in c["bot_candidates"] if b not in skew_only]
    excluded = [b for b in c["bot_candidates"] if decision(b["login"], d) != "Human, kept"]

    head = r"""    \toprule
    \textbf{Account} & \textbf{C} & \textbf{PR} & \textbf{I} & \textbf{Detection reason(s)} & \textbf{Decision} \\
    \midrule"""
    rows = []
    for b in listed:
        reasons = "; ".join(tex(r) for r in b["reasons"])
        rows.append(f"    \\texttt{{{tex(b['login'])}}} & {b['commits']} & {b['prs']} & {b['issues']} & {reasons} & {decision(b['login'], d)} \\\\")
    bot_table = "\n".join([
        "{",
        "\\small",
        "\\begin{xltabular}{\\linewidth}{@{} p{3.6cm} r r r X p{2.3cm} @{}}",
        f"    \\caption{{Bot Candidates Among the {c['population']:,} Census Accounts ({len(c['bot_candidates'])} Flagged, "
        f"{len(excluded)} Excluded; {len(skew_only)} Skew-Only Candidates Kept as Humans Are Not Listed). "
        "C = commits, PR = pull requests, I = issues.} \\label{tab:filtered_bots} \\\\".replace(",", "{,}", 1),
        head, "    \\endfirsthead",
        "    \\multicolumn{6}{@{}l}{\\small\\textit{Continued from previous page}} \\\\", head, "    \\endhead",
        "    \\midrule", "    \\multicolumn{6}{r@{}}{\\small\\textit{Continued on next page}} \\\\", "    \\endfoot",
        "    \\bottomrule", "    \\endlastfoot",
        *rows,
        "\\end{xltabular}",
        "}",
    ])

    alias_rows = []
    rejected = {tuple(sorted(p[:2])): p[2] for p in d["not_aliases"]}
    merged = {tuple(sorted((a, v["canonical"]))): v["reason"] for a, v in d["aliases"].items()}
    for p in c["alt_candidates"]:
        key = tuple(sorted(p["accounts"]))
        if key in merged:
            dec = "Same person, merged"
        elif key in rejected:
            dec = f"Kept separate: {tex(rejected[key])}"
        else:
            dec = "UNDECIDED"
        reasons = "; ".join(tex(r) for r in p["reasons"])
        alias_rows.append(f"    \\texttt{{{tex(key[0])}}} & \\texttt{{{tex(key[1])}}} & {reasons} & {dec} \\\\")
    n_merged = sum("merged" in r for r in alias_rows)
    alias_head = r"""    \toprule
    \textbf{Account} & \textbf{Linked account} & \textbf{Detection reason} & \textbf{Decision} \\
    \midrule"""
    alias_table = "\n".join([
        "{",
        "\\small",
        "\\begin{xltabular}{\\linewidth}{@{} p{2.9cm} p{2.9cm} X X @{}}",
        f"    \\caption{{Candidate Alternate Account Pairs ({len(c['alt_candidates'])} Flagged, {n_merged} Merged).}} "
        "\\label{tab:multiple_accounts} \\\\",
        alias_head, "    \\endfirsthead",
        "    \\multicolumn{4}{@{}l}{\\small\\textit{Continued from previous page}} \\\\", alias_head, "    \\endhead",
        "    \\midrule", "    \\multicolumn{4}{r@{}}{\\small\\textit{Continued on next page}} \\\\", "    \\endfoot",
        "    \\bottomrule", "    \\endlastfoot",
        *alias_rows,
        "\\end{xltabular}",
        "}",
    ])
    skew_list = ", ".join(f"\\texttt{{{tex(b['login'])}}}" for b in skew_only)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "% Auto-generated by final/project_health/make_appendix_tables.py\n"
        f"% BOT_TABLE\n{bot_table}\n\n% SKEW_ONLY\n{skew_list}\n\n% ALIAS_TABLE\n{alias_table}\n",
        encoding="utf-8",
    )
    print(f"{len(listed)} listed bot candidates, {len(skew_only)} skew-only, {len(excluded)} excluded, "
          f"{len(alias_rows)} pairs ({n_merged} merged); undecided: {sum('UNDECIDED' in r for r in alias_rows)}")


if __name__ == "__main__":
    main()
